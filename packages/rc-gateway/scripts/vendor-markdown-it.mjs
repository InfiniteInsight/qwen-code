/**
 * Regenerates public/vendor/markdown-it.js: a single minified ESM bundle of
 * markdown-it, the parser the web viewer uses to read assistant text. The
 * viewer is a static page with no client build step, so the library is vendored
 * as one file the page can `import()`. The bundle is the bare parser: no
 * instance and no options, so the safety settings (html off, linkify off) live
 * in transcript-view.js where they can be reviewed and tested. Run
 * `node scripts/vendor-markdown-it.mjs` from packages/rc-gateway after bumping
 * the devDependency (or esbuild); src/vendorMarkdownIt.test.ts fails until the
 * committed file matches.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';
import { build } from 'esbuild';

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(pkgDir, 'public', 'vendor', 'markdown-it.js');

function markdownItVersion() {
  const require = createRequire(join(pkgDir, 'package.json'));
  const manifest = require.resolve('markdown-it/package.json');
  return JSON.parse(readFileSync(manifest, 'utf8')).version;
}

/** Returns the bundle text (does not write it). */
export async function buildMarkdownIt() {
  const version = markdownItVersion();
  const result = await build({
    stdin: {
      // markdown-it's ESM entry has a default export and no named one, so the
      // bundle re-exports it under a name the viewer can destructure.
      contents:
        "import MarkdownIt from 'markdown-it';\nexport { MarkdownIt };\n",
      resolveDir: pkgDir,
    },
    bundle: true,
    format: 'esm',
    minify: true,
    write: false,
    banner: {
      js: `/* markdown-it ${version} (MIT) - generated by scripts/vendor-markdown-it.mjs; do not edit. See markdown-it.LICENSE */`,
    },
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildMarkdownIt();
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  process.stdout.write(`wrote ${outFile} (${text.length} bytes)\n`);
}
