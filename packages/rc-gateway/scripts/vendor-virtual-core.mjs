/**
 * Regenerates public/vendor/virtual-core.js: a single minified ESM bundle of
 * the pieces of @tanstack/virtual-core the web viewer imports. The viewer is a
 * static page with no client build step, so the library is vendored as one
 * file the page can `import()`. Run `node scripts/vendor-virtual-core.mjs`
 * from packages/rc-gateway after bumping the devDependency (or esbuild);
 * src/vendorVirtualCore.test.ts fails until the committed file matches.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';
import { build } from 'esbuild';

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(pkgDir, 'public', 'vendor', 'virtual-core.js');

function virtualCoreVersion() {
  const require = createRequire(join(pkgDir, 'package.json'));
  const manifest = require.resolve('@tanstack/virtual-core/package.json');
  return JSON.parse(readFileSync(manifest, 'utf8')).version;
}

/** Returns the bundle text (does not write it). */
export async function buildVirtualCore() {
  const version = virtualCoreVersion();
  const result = await build({
    stdin: {
      contents:
        "export { Virtualizer, observeElementRect, observeElementOffset, elementScroll } from '@tanstack/virtual-core';",
      resolveDir: pkgDir,
    },
    bundle: true,
    format: 'esm',
    minify: true,
    write: false,
    banner: {
      js: `/* @tanstack/virtual-core ${version} (MIT) - generated by scripts/vendor-virtual-core.mjs; do not edit. See virtual-core.LICENSE */`,
    },
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildVirtualCore();
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, text);
  process.stdout.write(`wrote ${outFile} (${text.length} bytes)\n`);
}
